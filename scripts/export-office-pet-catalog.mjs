import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { OFFICE_VERSION } from '../packages/agent-contracts/office.js';
import { OFFICE_ROLE_CATALOG_VERSION, OFFICE_ROLE_CATALOG, OFFICE_NOTICE_OWNERS } from '../packages/agent-contracts/office-role-catalog.js';

const defaultOutput = fileURLToPath(new URL('../prototypes/moonlight-pet-macos/Sources/MoonlightPetPreview/Models/OfficeRoleCatalog.generated.swift', import.meta.url));

export function swiftStringLiteral(value) {
  const escapes = { '"': '\\"', '\\': '\\\\', '\n': '\\n', '\r': '\\r', '\t': '\\t' };
  let literal = '"';
  for (const character of value) {
    const code = character.codePointAt(0);
    if (code >= 0xd800 && code <= 0xdfff) throw new TypeError('Swift strings require valid Unicode, not an unpaired surrogate.');
    literal += escapes[character] ?? (code < 0x20 || (code >= 0x7f && code <= 0x9f) || code === 0x2028 || code === 0x2029
      ? `\\u{${code.toString(16)}}` : character);
  }
  return `${literal}"`;
}

export function renderOfficePetCatalog() {
  const quote = swiftStringLiteral;
  const roles = Object.values(OFFICE_ROLE_CATALOG).map(role => [
    `        ${quote(role.id)}: OfficeRoleMetadata(`,
    ...['id', 'name', 'role', 'responsibility'].map(key => `            ${key}: ${quote(role[key])},`),
    `            starters: [${role.starters.map(quote).join(', ')}],`,
    `            handoff: ${quote(role.handoff)}`,
    '        ),',
  ].join('\n')).join('\n');
  const owners = Object.entries(OFFICE_NOTICE_OWNERS).map(([kind, owner]) => `        ${quote(kind)}: ${quote(owner)},`).join('\n');
  return `// Generated by scripts/export-office-pet-catalog.mjs. Do not edit directly.
// Sources: packages/agent-contracts/office-role-catalog.js and office.js.
// Catalog: ${OFFICE_ROLE_CATALOG_VERSION}; identity: ${OFFICE_VERSION}.
import Foundation

struct OfficeRoleMetadata: Sendable {
    let id: String
    let name: String
    let role: String
    let responsibility: String
    let starters: [String]
    let handoff: String
}

enum OfficeRoleCatalog {
    static let version = ${quote(OFFICE_ROLE_CATALOG_VERSION)}
    static let roles: [String: OfficeRoleMetadata] = [
${roles}
    ]

    static let noticeOwners: [String: String] = [
${owners}
    ]

    static func noticeOwner(for kind: String, actualOwnerId: String? = nil) -> String? {
        if kind == "agentReply" {
            guard let owner = actualOwnerId, roles[owner] != nil else { return nil }
            return owner
        }
        return noticeOwners[kind]
    }
}
`;
}

async function main() {
  const { values } = parseArgs({ options: { output: { type: 'string' }, check: { type: 'boolean', default: false } } });
  const output = values.output ? resolve(values.output) : defaultOutput;
  const content = renderOfficePetCatalog();
  if (values.check) {
    let existing;
    try { existing = await readFile(output, 'utf8'); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (existing !== content) {
      console.error(`Office pet catalog is ${existing === undefined ? 'missing' : 'stale'}: ${output}\nRun node scripts/export-office-pet-catalog.mjs to regenerate the committed catalog.`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(output, content);
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
