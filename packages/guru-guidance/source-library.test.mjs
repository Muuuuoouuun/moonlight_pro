test('every Guru card person resolves to an original entry', () => {
  const personIds = [...new Set(GURU_CARDS.map(card => card.personId))];
  for (const personId of personIds) {
    const own = getPersonSource(personId);
    const hosted = HOSTED_PEOPLE[personId];
    assert.ok(Boolean(own) !== Boolean(hosted), `${personId}: needs its own entry or a reviewed HOSTED_PEOPLE row`);
    for (const card of GURU_CARDS.filter(item => item.personId === personId)) {
      const resolved = resolveCardSource(card);
      assert.ok(resolved?.entry, card.id);
      assert.equal(resolved.entry.id, own ? own.id : hosted.entryId, card.id);
      assert.equal(resolved.hosted, Boolean(hosted), card.id);
      assert.equal(resolved.entries.length, 1, card.id);
    }
  }
  assert.ok(Object.keys(HOSTED_PEOPLE).every(personId => personIds.includes(personId)), 'no stale hosted rows');
  // The card person ids come from GURU_CARDS; the originals reuse them verbatim.
  for (const personId of ['zig-ziglar', 'dale-carnegie', 'neil-rackham', 'chris-voss', 'aaron-ross', 'keenan',
    'seth-godin', 'david-ogilvy', 'donald-miller', 'kane-kallaway', 'harry-dry', 'justin-welsh', 'dan-koe']) {
    assert.equal(getPersonSource(personId)?.personId, personId, personId);
  }
});

test('every Guru card section resolves to a heading or a reviewed exception', () => {
  for (const card of GURU_CARDS) {
    const resolved = resolveCardSource(card);
    const exception = SECTION_EXCEPTIONS[card.id];
    assert.ok(resolved.heading, `${card.id}: "${card.source.section}" found no heading`);
    if (exception) {
      assert.ok(exception.reason.length > 20, card.id);
      assert.equal(resolved.approximate, true, `${card.id} no longer needs its exception`);
      assert.equal(resolved.heading.text, exception.heading, card.id);
    } else {
      assert.equal(resolved.approximate, false, `${card.id}: "${card.source.section}" matched only approximately — review it`);
      assert.ok(['exact', 'contains', 'segment'].includes(resolved.method), card.id);
    }
  }
  assert.ok(Object.keys(SECTION_EXCEPTIONS).every(id => GURU_CARDS.some(card => card.id === id)), 'no stale exceptions');
  const meddic = resolveCardSource(GURU_CARDS.find(card => card.id === 'sales-meddic'));
  assert.equal(meddic.heading.text, '기법 4: **Qualification — MEDDIC 프레임워크**');
  const plan = resolveCardSource(GURU_CARDS.find(card => card.id === 'marketing-clear-plan'));
  assert.equal(plan.heading.text, '4단계: 계획 — 불확실성을 제거하라');
});

test('Legend cards and all sixteen Legend ids resolve by id, never by source path', () => {
  const ids = Object.keys(LEGEND_MICRO_CARDS);
  assert.equal(ids.length, 16);
  const legendEntries = SOURCE_ENTRIES.filter(entry => entry.legendId);
  assert.deepEqual(new Set(legendEntries.map(entry => entry.legendId)), new Set(ids));
  for (const id of ids) {
    const entries = getLegendSources(id);
    assert.ok(entries.some(entry => entry.collection === 'legend-framework'), `${id} has its 2026-09-21 micro-card`);
    assert.ok(entries.every(entry => entry.name === LEGEND_MICRO_CARDS[id].name), id);
    assert.deepEqual(entries.map(entry => entry.collection), [...entries.map(entry => entry.collection)].sort().reverse(), `${id}: long card first`);
  }
  assert.equal(listSourceEntries({ collection: 'legend-values', kind: 'person' }).length, 9);
  for (const card of LEGEND_CARDS) {
    const moved = { ...card, source: { ...card.source, path: 'somewhere/else.ts', section: 'unrelated' } };
    for (const candidate of [card, moved]) {
      const resolved = resolveCardSource(candidate);
      assert.equal(resolved?.kind, 'legend', card.id);
      assert.equal(resolved.legendId, legendIdFromCardId(card.id));
      assert.deepEqual(resolved.entries, getLegendSources(card.id));
    }
  }
  assert.deepEqual(getLegendSources('legend-buffett').map(entry => entry.id), ['legend-values.buffett', 'legend-framework.buffett']);
  assert.deepEqual(getLegendSources('feynman').map(entry => entry.id), ['legend-framework.feynman']);
  assert.deepEqual(getLegendSources('unknown'), []);
});

