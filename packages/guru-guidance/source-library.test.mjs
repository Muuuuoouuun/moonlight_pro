test('committed generated modules equal a fresh generation from the original documents', () => {
  for (const [path, content] of renderOutputs(buildSourceLibrary({ root: repoRoot }))) {
    const committed = readNormalized(path);
    assert.ok(committed === content, `${path} is stale — run npm run guidance:sources`);
    assert.match(committed, /^\/\/ GENERATED by scripts\/build-guidance-source-library\.mjs — do not edit\./);
  }
  assert.deepEqual([LIBRARY_OUTPUT, PEOPLE_OUTPUT], [
    'packages/guru-guidance/source-library.generated.js',
    'packages/guru-guidance/source-people.generated.js',
  ]);
});

test('generation is byte-identical for CRLF and LF checkouts, and --check fails only when stale', () => {
  const inputs = [QUALITY_REVIEW_PATH, ...SOURCE_CONFIG.map(doc => doc.path)];
  const makeRoot = eol => {
    const root = mkdtempSync(join(tmpdir(), `guidance-sources-${eol === '\r\n' ? 'crlf' : 'lf'}-`));
    for (const path of [...inputs, LIBRARY_OUTPUT, PEOPLE_OUTPUT]) {
      mkdirSync(dirname(join(root, path)), { recursive: true });
      writeFileSync(join(root, path), readNormalized(path).replace(/\n/g, eol));
    }
    return root;
  };
  const crlf = makeRoot('\r\n');
  const lf = makeRoot('\n');
  const log = console.log;
  const error = console.error;
  console.log = () => {};
  console.error = () => {};
  try {
    assert.deepEqual(renderOutputs(buildSourceLibrary({ root: crlf })), renderOutputs(buildSourceLibrary({ root: lf })));
    assert.equal(main(['--check'], { root: crlf }), 0, 'a CRLF working copy of the generated file still counts as current');
    writeFileSync(join(lf, LIBRARY_OUTPUT), readNormalized(LIBRARY_OUTPUT).replace('"sales.zig-ziglar"', '"sales.edited"'));
    assert.equal(main(['--check'], { root: lf }), 1, 'an edited generated file is reported stale');
    assert.equal(main([], { root: lf }), 0);
    assert.equal(main(['--check'], { root: lf }), 0);
    assert.ok(!readFileSync(join(lf, LIBRARY_OUTPUT), 'utf8').includes('\r'), 'written with LF on every OS');
    writeFileSync(join(lf, SOURCE_CONFIG[1].path), readNormalized(SOURCE_CONFIG[1].path).replace('# 2. 데이비드 오길비 (David Ogilvy)', '# 2. 오길비'));
    assert.throws(() => buildSourceLibrary({ root: lf }), /boundary heading "# 2\. 데이비드 오길비 \(David Ogilvy\)" matched 0 lines/);
  } finally {
    console.log = log;
    console.error = error;
    rmSync(crlf, { recursive: true, force: true });
    rmSync(lf, { recursive: true, force: true });
  }
});

test('every line of every document belongs to exactly one entry, reproducing it byte for byte', () => {
  assert.deepEqual(SOURCE_DOCUMENTS.map(doc => doc.path), [
    'docs/sales-guru-knowledge-base.md',
    'docs/marketing-branding-gurus.md',
    'docs/content-storytelling-people-v2.md',
    'docs/superpowers/specs/2026-09-12-legend-values-persona-cards.md',
    'docs/superpowers/specs/2026-09-21-council-mentor-guru-legend-operating-framework.md',
  ]);
  for (const doc of SOURCE_DOCUMENTS) {
    const text = readNormalized(doc.path);
    assert.ok(!text.includes('\r'), `${doc.path} is LF-normalized`);
    const lines = splitSourceLines(text);
    assert.equal(doc.sha256, sha256(text), doc.path);
    assert.equal(doc.lineCount, lines.length, doc.path);
    assert.equal(doc.charCount, [...text].length, doc.path);
    assert.equal(`# ${doc.title}\n`, lines[0], `${doc.path} title is its own H1`);
    const entries = listSourceEntries({ collection: doc.collection });
    assert.ok(entries.length > 1, doc.path);
    assert.equal(entries[0].startLine, 1);
    assert.equal(entries[entries.length - 1].endLine, lines.length);
    entries.forEach((entry, index) => {
      if (index) assert.equal(entry.startLine, entries[index - 1].endLine + 1, `${entry.id} follows the previous entry without a gap or overlap`);
      assert.ok(entry.startLine <= entry.endLine, entry.id);
      assert.equal(entry.docPath, doc.path);
      assert.equal(entry.markdown, lines.slice(entry.startLine - 1, entry.endLine).join(''), `${entry.id} is a verbatim slice`);
      assert.equal(entry.charCount, [...entry.markdown].length, entry.id);
    });
    assert.equal(entries.map(entry => entry.markdown).join(''), text, `${doc.path} concatenates back exactly`);
  }
  assert.equal(SOURCE_ENTRIES.length, SOURCE_DOCUMENTS.reduce((sum, doc) => sum + listSourceEntries({ collection: doc.collection }).length, 0));
});

test('entries carry only verbatim text plus positional metadata', () => {
  const allowed = new Set(['id', 'collection', 'kind', 'personId', 'legendId', 'name', 'title', 'docPath', 'startLine', 'endLine', 'charCount', 'headings', 'markdown']);
  for (const entry of SOURCE_ENTRIES) {
    assert.deepEqual(Object.keys(entry).filter(key => !allowed.has(key)), [], entry.id);
    assert.ok(['person', 'synthesis', 'preface'].includes(entry.kind), entry.id);
    assert.match(entry.id, new RegExp(`^${entry.collection}\\.[a-z0-9]+(?:-[a-z0-9]+)*$`));
    const firstLine = entry.markdown.split('\n')[0];
    assert.match(firstLine, /^#{1,6} /, `${entry.id} starts at a heading boundary`);
    assert.equal(firstLine.replace(/^#{1,6} /, ''), entry.title, `${entry.id} title is the heading text, unedited`);
    assert.equal(entry.headings[0].line, entry.startLine, entry.id);
    const lines = entry.markdown.split('\n');
    for (const heading of entry.headings) {
      assert.ok(heading.line >= entry.startLine && heading.line <= entry.endLine, `${entry.id}@${heading.line}`);
      assert.equal(lines[heading.line - entry.startLine], `${'#'.repeat(heading.level)} ${heading.text}`, `${entry.id}@${heading.line}`);
    }
    if (entry.kind === 'person') assert.ok(entry.name && (entry.personId || entry.legendId), entry.id);
    else assert.equal(entry.name, null, entry.id);
  }
  assert.deepEqual(new Set(SOURCE_ENTRIES.filter(entry => entry.kind === 'preface').map(entry => entry.collection)),
    new Set(SOURCE_DOCUMENTS.map(doc => doc.collection)));
});

